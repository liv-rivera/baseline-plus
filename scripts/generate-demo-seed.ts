// Writes database/seed.sql from the shared sample records in src/lib/sampleData.ts.
// Run with: npm run db:seed:generate
// Dates are written relative to CURRENT_DATE, so the demo account always shows
// the six weeks leading up to the day the seed is run.
import { writeFileSync } from "node:fs";
import { generateSampleMetrics, SAMPLE_DAYS } from "../src/lib/sampleData.ts";

const demoUserId = "00000000-0000-4000-8000-000000000001";
const rows = generateSampleMetrics("2026-01-31");
const quote = (value: string) => `'${value.replace(/'/g, "''")}'`;
const uuid = (group: string, n: number) => `'00000000-0000-0000-${group}-${String(n).padStart(12, "0")}'`;
const day = (index: number) => `CURRENT_DATE - ${SAMPLE_DAYS - 1 - index}`;

const metrics: string[] = [];
const contributions: string[] = [];
const checkIns: string[] = [];
let contributionId = 0;

rows.forEach((row, index) => {
  const metricId = uuid("0003", index + 1);
  metrics.push(`    (${metricId}, ${quote(demoUserId)}, ${day(index)}, ${row.steps}, ${row.moveCalories}, ${row.restMinutes}, ${row.breatheMinutes}, ${row.readinessScore}, 'demo')`);
  const add = (type: string, name: string, minutes: number, quantity: number) =>
    contributions.push(`    (${uuid("0004", ++contributionId)}, ${metricId}, '${type}', ${quote(name)}, ${minutes}, ${quantity})`);
  row.activities.forEach((a) => add("move_calories", a.name, a.durationMinutes, a.calories));
  row.stepActivities.forEach((a) => add("steps", a.name, a.durationMinutes, a.steps));
  row.restPeriods.forEach((r) => add("rest", r.name, r.durationMinutes, r.durationMinutes));
  row.breathworkSessions.forEach((b) => add("breathwork", b.name, b.durationMinutes, b.durationMinutes));
  if (row.checkIn) {
    checkIns.push(`    (${quote(demoUserId)}, ${day(index)}, ${row.checkIn.energy ?? "NULL"}, ${row.checkIn.soreness ?? "NULL"})`);
  }
});

const sql = `-- Generated by scripts/generate-demo-seed.ts from src/lib/sampleData.ts. Do not edit by hand.
-- Re-running this seed resets the demo account's records to six fictional weeks ending today.
BEGIN;

INSERT INTO users (id, email, display_name)
VALUES (${quote(demoUserId)}, 'demo@baseline.example', 'Baseline Demo')
ON CONFLICT (id) DO NOTHING;

DELETE FROM daily_check_ins WHERE user_id = ${quote(demoUserId)};
DELETE FROM daily_metrics WHERE user_id = ${quote(demoUserId)};

INSERT INTO daily_metrics (
    id, user_id, metric_date, steps, move_calories, rest_minutes,
    breathwork_minutes, readiness_score, source
)
VALUES
${metrics.join(",\n")};

INSERT INTO metric_contributions (id, daily_metric_id, metric_type, name, duration_minutes, quantity)
VALUES
${contributions.join(",\n")};

INSERT INTO daily_check_ins (user_id, local_date, energy, soreness)
VALUES
${checkIns.join(",\n")};

COMMIT;
`;

writeFileSync(new URL("../database/seed.sql", import.meta.url), sql);
console.info(`Wrote database/seed.sql: ${rows.length} days, ${contributionId} contributions, ${checkIns.length} check-ins.`);
